//11. Faça um programa que leia um número e diga se ele é par ou ímpar.
public class parImpar {
    public static void main(String[] args) {
        int num = 10;

        if (num%2==0){
            System.out.println("par");
        }else{
            System.out.println("impar");
        }
    }
}
